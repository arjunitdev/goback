/* global document, getComputedStyle -- these run inside the browser page via evaluate() */
// Generates src/styles/youtube/theme-light.generated.css (run: npm run gen:yt-theme).
//
// YouTube picks its dark theme on the SERVER and writes dark colour values straight onto
// <html> as CSS custom properties, so there is no attribute to flip. This script loads the
// same public, logged-out page once in each theme, diffs every custom property, and writes
// the light value for each property that differs. The Authentic mode stylesheet then
// pins those variables to light, giving the 2012 look for people who use dark mode.
//
// The output is interoperability data (variable names and colour values), regenerated
// whenever YouTube renames its tokens. If it goes stale the engine detects the page is still
// dark and withholds the palette, so text stays readable (see detectScheme).
//
// MANUAL tool: makes two page loads of youtube.com. Never run it in CI.
import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';

const URL_TO_LOAD = 'https://www.youtube.com/results?search_query=music';
const browser = await chromium.launch({ channel: 'chromium' });
const seen = {};

for (const scheme of ['light', 'dark']) {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  // YouTube stores the theme in the PREF cookie: f6=400 is dark.
  if (scheme === 'dark') {
    await ctx.addCookies([
      { name: 'PREF', value: 'f6=400&tz=UTC', domain: '.youtube.com', path: '/', secure: true },
    ]);
  }
  const page = await ctx.newPage();
  await page.goto(URL_TO_LOAD, { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(7000);
  seen[scheme] = await page.evaluate(() => {
    const names = new Set();
    for (const sheet of document.styleSheets) {
      let rules;
      try {
        rules = sheet.cssRules;
      } catch {
        continue;
      }
      for (const r of rules)
        if (r.style) for (const n of r.style) if (n.startsWith('--')) names.add(n);
    }
    const html = getComputedStyle(document.documentElement);
    const app = getComputedStyle(document.querySelector('ytd-app'));
    const out = {};
    for (const n of names) out[n] = (html.getPropertyValue(n) || app.getPropertyValue(n)).trim();
    return { vars: out, isDark: document.documentElement.hasAttribute('dark') };
  });
  await ctx.close();
}
await browser.close();

if (seen.light.isDark || !seen.dark.isDark) {
  throw new Error(
    'Theme cookie did not take effect (light page was dark, or dark page was light).',
  );
}

const lines = [];
for (const [name, light] of Object.entries(seen.light.vars).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const dark = seen.dark.vars[name];
  if (light && dark && light !== dark) lines.push(`  ${name}: ${light} !important;`);
}
if (lines.length < 50)
  throw new Error(`Only ${lines.length} differing variables found; refusing to write.`);

const today = new Date().toISOString().slice(0, 10);
const css = `/*
 * GENERATED by scripts/gen-youtube-theme.mjs on ${today}. Do not edit by hand.
 * ${lines.length} YouTube theme variables pinned to their LIGHT values in Authentic mode,
 * because the 2012 site had no dark theme. If YouTube renames its tokens this goes stale:
 * the engine then measures the page as dark and withholds the 2012 palette (readable, not 2012).
 */
html[data-retroweb='youtube'][data-retroweb-mode='authentic'],
html[data-retroweb='youtube'][data-retroweb-mode='authentic'] ytd-masthead {
${lines.join('\n')}
}
`;
writeFileSync(new URL('../src/styles/youtube/theme-light.generated.css', import.meta.url), css);
console.log(`wrote ${lines.length} variables`);
