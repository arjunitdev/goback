/* global document, getComputedStyle -- these run inside the browser page via evaluate() */
// Generates src/styles/google/theme-light.generated.css (run: npm run gen:google-theme).
//
// Google themes its pages with CSS custom properties on <html> and chooses light or dark on the
// SERVER, so there is no attribute to flip. This script loads the same public, logged-out home
// page repeatedly in one throwaway browser profile, keeps one dark load and one light load
// (told apart by the measured body background), diffs every custom property, and writes the
// light value for each property that differs. Authentic mode pins those variables to light, which
// gives the 2012 look to people whose Google is dark. Same method as scripts/gen-youtube-theme.mjs.
//
// If Google renames its tokens the pin goes stale; the engine then measures the page as dark and
// withholds the 2012 palette, so text stays readable (see detectScheme).
//
// MANUAL tool: makes up to six page loads of google.com. Never run it in CI.
import { chromium } from '@playwright/test';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const browser = await chromium.launchPersistentContext(mkdtempSync(join(tmpdir(), 'rw-gg-')), {
  channel: 'chromium',
  viewport: { width: 1280, height: 800 },
});
const page = await browser.newPage();
const seen = {};

for (let i = 0; i < 6 && !(seen.light && seen.dark); i += 1) {
  await page.goto(`https://www.google.com/?hl=en&n=${i}`, { waitUntil: 'load' });
  await page.waitForTimeout(2500);
  const snap = await page.evaluate(() => {
    const names = new Set();
    const walk = (rules) => {
      for (const r of rules) {
        if (r.cssRules) walk(r.cssRules);
        if (r.style) for (const n of r.style) if (n.startsWith('--')) names.add(n);
      }
    };
    for (const sheet of document.styleSheets) {
      try {
        walk(sheet.cssRules);
      } catch {
        // cross-origin sheet: not readable, not ours to pin
      }
    }
    const html = getComputedStyle(document.documentElement);
    const vars = {};
    for (const n of names) vars[n] = html.getPropertyValue(n).trim();
    const m = /rgba?\((\d+),\s*(\d+),\s*(\d+)/.exec(getComputedStyle(document.body).backgroundColor);
    const lum = m ? (0.299 * +m[1] + 0.587 * +m[2] + 0.114 * +m[3]) / 255 : 1;
    return { vars, dark: lum < 0.3 };
  });
  seen[snap.dark ? 'dark' : 'light'] ??= snap.vars;
}
await browser.close();

if (!seen.light || !seen.dark) {
  throw new Error(
    'Did not observe both a light and a dark Google page in six loads; refusing to write.',
  );
}

const lines = [];
for (const [name, light] of Object.entries(seen.light).sort(([a], [b]) => a.localeCompare(b))) {
  const dark = seen.dark[name];
  if (light && dark && light !== dark) lines.push(`  ${name}: ${light} !important;`);
}
if (lines.length < 20) {
  throw new Error(`Only ${lines.length} differing variables found; refusing to write.`);
}

const today = new Date().toISOString().slice(0, 10);
const css = `/*
 * GENERATED by scripts/gen-google-theme.mjs on ${today}. Do not edit by hand.
 * ${lines.length} Google theme variables pinned to their LIGHT values in Authentic mode, because
 * the 2012 site had no dark theme. If Google renames its tokens this goes stale: the engine then
 * measures the page as dark and withholds the 2012 palette (readable, not 2012).
 */
html[data-retroweb='google'][data-retroweb-mode='authentic'] {
${lines.join('\n')}
}
`;
writeFileSync(new URL('../src/styles/google/theme-light.generated.css', import.meta.url), css);
console.log(`wrote ${lines.length} variables`);
